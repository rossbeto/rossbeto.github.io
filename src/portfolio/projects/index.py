"""Render the projects index page and the home page's featured cards. Pure: in → Markdown."""

import json
import posixpath
from collections.abc import Iterable

from portfolio.projects.model import KIND_LABEL, Project

INDEX_PAGE = "projects/index.md"
HOME_PAGE = "index.md"
EMPTY = "The first write-up is on its way."
DESCRIPTION = (
    "Personal labs and public work: what each project shows, how it is tested, and what I learned."
)


def ordered(projects: Iterable[Project]) -> list[Project]:
    """Featured first, then `order`, then title."""
    return sorted(projects, key=lambda p: (not p.meta.featured, p.meta.order, p.meta.title))


def _rel(target: str, page: str) -> str:
    return posixpath.relpath(target, posixpath.dirname(page) or ".")


def _cards(projects: list[Project], page: str) -> str:
    out = ['<div class="grid cards" markdown>', ""]
    for p in projects:
        m, link = p.meta, _rel(p.src, page)
        out.append(f"-   **[{m.title}]({link})**")
        out.append("")
        out.append(f"    {KIND_LABEL[m.kind]} · {m.stage.value}")
        out.append("")
        if m.image:
            out.append(f"    [![{m.image_alt}]({_rel(m.image, page)}){{ loading=lazy }}]({link})")
            out.append("")
        out.append(f"    {m.summary}")
        out.append("")
        out.append("    " + " ".join(f"`{t}`" for t in m.tags))
        out.append("")
        repo = f"[Repository]({m.repo})" if m.repo_public else "Repository: publishing soon"
        out.append(f"    [:octicons-arrow-right-24: Case study]({link}) · {repo}")
        out.append("")
    out.append("</div>")
    return "\n".join(out) + "\n"


def render_project_index(projects: Iterable[Project]) -> str:
    chosen = ordered(projects)
    head = (
        "---\ntitle: Projects\n"
        f"description: {json.dumps(DESCRIPTION)}\n"
        "---\n\n"
        "<!-- Generated by `portfolio generate` from docs/projects/*.md front matter. -->\n\n"
        "# Projects\n\n"
        "Systems I built end to end, each with the tests that prove it. Personal labs are\n"
        "labelled as such: their numbers are test numbers, not production traffic.\n\n"
    )
    return head + (_cards(chosen, INDEX_PAGE) if chosen else EMPTY + "\n")


def render_featured(projects: Iterable[Project], limit: int = 3) -> str:
    chosen = [p for p in ordered(projects) if p.meta.featured][:limit]
    return _cards(chosen, HOME_PAGE) if chosen else EMPTY + "\n"
