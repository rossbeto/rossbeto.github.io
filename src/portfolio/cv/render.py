"""Render the CV for the site. Pure: model in, text out (templates ship inside the package)."""

import html
import json
import posixpath
import re

from jinja2 import Environment, PackageLoader, StrictUndefined

from portfolio.cv.model import CV

CV_PAGE = "cv/index.md"  # where the page lives under docs/; links are made relative to it


def _cell(value: str) -> str:
    """Text safe inside a Markdown table cell."""
    return value.replace("|", "\\|").replace("\n", " ")


def _link(target: str) -> str:
    return posixpath.relpath(target, posixpath.dirname(CV_PAGE))


_env = Environment(
    loader=PackageLoader("portfolio", "templates"),
    undefined=StrictUndefined,
    autoescape=False,  # Markdown, not HTML  # noqa: S701
    keep_trailing_newline=True,
)
_env.filters["cell"] = _cell


def render_cv_markdown(cv: CV, *, pdf_url: str | None = None) -> str:
    text = _env.get_template("cv.md.j2").render(
        cv=cv,
        capabilities=[c for c in cv.capabilities if not c.hidden],
        work=[w for w in cv.work if not w.hidden],
        pdf_url=pdf_url,
        link=_link,
    )
    return re.sub(r"\n{3,}", "\n\n", text)  # the template's optional sections leave gaps


def profile_context(cv: CV) -> dict[str, object]:
    """What overrides/partials/profile.html shows in the left column."""
    b = cv.basics
    return {
        "name": b.name,
        "label": b.label,
        "location": f"{b.location.city}, {b.location.region}",
        "image": b.image,
        "image_alt": b.image_alt,
        "links": [{"name": p.network, "url": p.url, "icon": p.icon} for p in b.profiles],
    }


def render_profile_data(cv: CV) -> str:
    """A Jinja file for the theme: `{% set profile = {...} %}`, imported by profile.html.

    JSON literals of strings, lists and objects are valid Jinja literals; `json.dumps` escapes
    quotes and backslashes, and the model holds no booleans or numbers here.
    """
    data = json.dumps(profile_context(cv), ensure_ascii=False, indent=2)
    if "{{" in data or "{%" in data or "{#" in data:
        raise ValueError("profile values must not contain Jinja delimiters")
    return (
        "{#- Generated by `portfolio generate` from data/cv.yml: edit the data. -#}\n"
        f"{{% set profile = {data} %}}\n"
    )


def render_home_header(cv: CV) -> str:
    """The compact profile shown on the home page on phones (the left column is hidden there)."""
    b = cv.basics
    name, label, city = (html.escape(v) for v in (b.name, b.label, b.location.city))
    return (
        '<div class="home-profile" markdown>\n'
        f"![{b.image_alt}]({b.image})\n"
        f"<p><strong>{name}</strong><br>{label} · {city}</p>\n"
        "</div>\n"
    )
